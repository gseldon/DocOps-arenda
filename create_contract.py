#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Скрипт для создания договора аренды квартиры в формате DOCX.

Запуск:
    python3 create_contract.py [--data contract_data.json] [--check] [-o файл.docx]
"""

import sys

from contract_utils import (
    blank, counted, fmt_percent, full_address, load_contract_data, long_date, money,
    quoted_date, run_cli)
from docx_builder import page_break, paragraph, paragraph_split, table, write_docx

__all__ = ['load_contract_data', 'create_contract_body', 'create_docx']


def create_contract_body(data):
    """Создает тело договора (XML). Все значения берутся из data."""
    body = []

    def p(text='', **kw):
        body.append(paragraph(text, **kw))

    def gap():
        body.append(paragraph('', size=24))

    landlord = data['landlord']
    tenant = data['tenant']
    prop = data['property']
    addr = prop['address']
    financial = data['financial']
    bank = data['bank_details']
    contract = data['contract']
    rules = data['rules']

    address = full_address(addr)
    conclusion = quoted_date(contract['conclusion_date'])
    start = long_date(contract['start_date'])
    cadastre = 'кадастровый номер {}, общая площадь {} м2'.format(
        prop['cadastral_number'], prop['area'])

    # Параметры с согласованными числом и прописью
    duration = counted(contract['duration_months'], 'month')
    prolongation = counted(contract['prolongation_months'], 'month')
    prolong_notice = counted(rules['prolongation_notice_days'], 'cal_day')
    index_notice = counted(rules['indexation_notice_days'], 'cal_day')
    residents = counted(rules['max_additional_residents'], 'person')
    resident_notice = counted(rules['notification_days_for_residents'], 'day')
    keys = counted(contract['keys_count'], 'keys')
    deposit_return = counted(rules['deposit_return_days'], 'cal_day', 'gen')
    utility_days = counted(rules['utility_payment_days'], 'work_day', 'gen')
    termination_notice = counted(rules['termination_notice_days'], 'cal_day')
    eviction = counted(rules['eviction_days'], 'cal_day', 'gen')

    # Заголовок
    p('Договор аренды помещения для проживания', bold=True, align='center', size=28)
    p('(далее – Договор)', bold=True, align='center', size=28)
    gap()
    body.append(paragraph_split('г. {}'.format(addr['city']), conclusion))
    gap()

    # Таблица реквизитов сторон
    def passport(person):
        return 'Паспорт серии {} № {},'.format(
            blank(person['passport_series'], 7), blank(person['passport_number'], 11))

    def issued(person):
        by = blank(person['passport_issued_by'], 35)
        date = person['passport_issued_date'].strip()
        return 'выдан {}{}'.format(by, ', ' + date if date else '')

    parties_rows = [
        ['Арендодатель:', 'Арендатор:'],
        ['', ''],
        ['Гр. РФ {} (ФИО)'.format(landlord['full_name']), 'Гр. РФ {} (ФИО)'.format(tenant['full_name'])],
        [passport(landlord), passport(tenant)],
        [issued(landlord), issued(tenant)],
        ['_' * 41, '_' * 41],
        ['Адрес регистрации: {}'.format(blank(landlord['registration_address'], 24)),
         'Адрес регистрации: {}'.format(blank(tenant['registration_address'], 24))],
        ['_' * 41, '_' * 41],
        ['Тел.: {}'.format(blank(landlord['phone'], 36)), 'Тел.: {}'.format(blank(tenant['phone'], 36))],
        ['Email: {}'.format(blank(landlord['email'], 35)), 'Email: {}'.format(blank(tenant['email'], 35))],
    ]
    body.append(table(parties_rows, font_size=20))
    gap()

    # Информация о помещении (строки на всю ширину таблицы)
    property_rows = [
        ['Помещение: {} / Комната'.format(prop['type'])],
        ['Адрес: {};'.format(address)],
        ['Кадастровый номер: {}; Общая площадь {} м2.'.format(prop['cadastral_number'], prop['area'])],
        ['• Принадлежит Арендодателю на праве собственности, что подтверждается Свидетельством о государственной регистрации права (при наличии) и (или) Выпиской из Единого государственного реестра недвижимости.'],
        ['• Не является предметом спора, не находится под арестом, не сдано в аренду/наем иным лицам.'],
        ['• Пригодно для проживания. Состояние Помещения указывается Сторонами в акте приема-передачи Помещения.'],
    ]
    body.append(table(property_rows, font_size=20))
    gap()

    # 1. Предмет Договора
    p('1. Предмет Договора.', bold=True, size=26)
    p('1.1. По Договору Арендодатель обязуется за плату предоставить Арендатору во владение и пользование Помещение для проживания в нем.')
    p('1.2. Договор вступает в силу с даты его подписания Сторонами и действует до истечения срока аренды.')
    p('1.3. Срок аренды: {}, начиная с «{}».'.format(duration, contract['start_date']))
    p('1.4. Помещение принадлежит Арендодателю на праве {}. Согласия третьих лиц на заключение настоящего Договора не требуется.'.format(prop['ownership']))
    p('1.5. АВТОМАТИЧЕСКАЯ ПРОЛОНГАЦИЯ: Если ни одна из Сторон не уведомит другую Сторону о намерении расторгнуть Договор не менее чем за {} до окончания срока его действия, Договор считается автоматически продленным на тех же условиях на новый срок {}.'.format(prolong_notice, prolongation))
    p('1.5.1. ИНДЕКСАЦИЯ АРЕНДНОЙ ПЛАТЫ: При автоматической пролонгации Договора размер арендной платы может быть увеличен Арендодателем, но не более чем на уровень официальной инфляции (индекса потребительских цен) в Российской Федерации за предыдущий календарный год, по данным Федеральной службы государственной статистики (Росстат). Арендодатель обязан уведомить Арендатора о новом размере арендной платы не менее чем за {} до начала нового срока аренды.'.format(index_notice))
    p('1.6. ПРОЖИВАЮЩИЕ ЛИЦА И ЖИВОТНЫЕ:', bold=True)
    p('1.6.1. В соответствии с настоящим Договором в Помещении проживает Арендатор. Арендатор имеет право вселить для постоянного проживания {} с обязательным письменным уведомлением Арендодателя не менее чем за {} до вселения с указанием ФИО и степени родства. Вселение третьих лиц без уведомления или свыше установленного лимита является основанием для расторжения Договора.'.format(residents, resident_notice))
    if rules['animals_allowed_by_default']:
        p('1.6.2. Содержание домашних животных в Помещении разрешено. Арендатор несет полную ответственность за любой ущерб, нанесенный животными Помещению и имуществу.')
    else:
        p('1.6.2. Нахождение в Помещении домашних животных ЗАПРЕЩЕНО. По письменному согласованию Сторон (оформляется отдельным дополнительным соглашением к настоящему Договору) может быть разрешено содержание домашних животных с указанием их вида и породы. При разрешении содержания животных Арендатор несет полную ответственность за любой ущерб, нанесенный животными Помещению и имуществу.')
    p('1.6.3. Арендатор обязуется использовать Помещение исключительно для проживания. Запрещается использование Помещения для субаренды, коммерческой деятельности, в качестве офиса или для иных целей, не связанных с проживанием.')
    gap()

    # 2. Приемка - передача Помещения
    p('2. Приемка – передача Помещения.', bold=True, size=26)
    p('2.1. Не позднее {} Арендодатель обязуется передать, а Арендатор принять {} ключей для доступа в Помещение.'.format(start, keys))
    p('2.2. Передача Помещения Арендатору осуществляется не позднее {} на основании акта приема передачи. Обратная передача Помещения от Арендатора к Арендодателю в любом случае осуществляется по акту возврата Помещения.'.format(start))
    p('2.3. В случае, если одна из Сторон не исполнила в срок или ненадлежащим образом исполнила обязанность, предусмотренную настоящим разделом, действие Договора прекращается в день истечения срока, представленного для исполнения обязанности и указанного в п. 2.1 или п 2.2. Договора соответственно.')
    gap()

    # 3. Расчеты
    p('3. Расчеты.', bold=True, size=26)
    p('3.1. Плата за аренду в месяц составляет {}.'.format(money(financial['monthly_rent'])))
    p('3.2. Оплата осуществляется не позднее {} числа (включительно) каждого календарного месяца, независимо от фактического срока проживания Арендатора в Помещении.'.format(financial['payment_period_end']))
    p('3.2.1. Плата за первый месяц пользования Помещением вносится Арендатором не позднее {}.'.format(long_date(financial['first_payment_deadline'])))
    p('3.2.2. В случае неоплаты за первый месяц пользования Помещением действие Договора прекращается в день истечения срока, предусмотренного настоящим пунктом.')
    p('3.3. Оплата арендной платы производится одним из следующих способов:')
    p('     - перевод по Системе быстрых платежей (СБП) по номеру телефона: {};'.format(financial['sbp_phone']))
    p('     - перевод на банковские реквизиты Арендодателя:')
    payment_details_rows = [
        ['Получатель:', bank['recipient']],
        ['Номер счета:', bank['account_number']],
        ['Назначение платежа:', bank['payment_purpose'].strip() or '—'],
        ['БИК:', bank['bik']],
        ['Банк-получатель:', bank['bank_name']],
        ['Корр. счет:', bank['correspondent_account']],
        ['ИНН:', bank['inn']],
        ['КПП:', bank.get('kpp', '').strip() or '—'],
    ]
    body.append(table(payment_details_rows, font_size=20, widths=[3000, 6355]))
    p('3.4. Обеспечительный платеж (залог) в размере {} вносится Арендатором не позднее {} тем же способом, что и арендная плата.'.format(
        money(financial['security_deposit']), long_date(financial['deposit_deadline'])))
    p('3.5. Обеспечительный платеж возвращается Арендатору в течение {} с момента возврата Помещения по Акту приема-передачи при условии отсутствия задолженности по арендной плате и коммунальным платежам, а также при отсутствии повреждений имущества и Помещения.'.format(deposit_return))
    p('3.6. В случае причинения Арендатором ущерба Помещению или имуществу, указанному в Описи, либо при наличии задолженности по арендной плате или коммунальным платежам, Арендодатель имеет право удержать из обеспечительного платежа сумму ущерба и/или задолженности, возвратив Арендатору оставшуюся часть.')
    gap()

    # 4. Права и обязанности Арендодателя
    p('4. Права и обязанности Арендодателя.', bold=True, size=26)
    p('4.1. Арендодатель обязуется:')
    p('4.1.1. Передать Помещение Арендатору в состоянии, пригодном для проживания, со всеми коммуникациями и инженерными системами в исправном состоянии.')
    p('4.1.2. Обеспечить Арендатору беспрепятственное пользование Помещением в течение всего срока действия Договора.')
    p('4.1.3. Производить за свой счет капитальный ремонт Помещения при необходимости, если такая необходимость возникла не по вине Арендатора.')
    p('4.1.4. В случае возникновения экстренных ситуаций (аварии, пожар, затопление, несанкционированный доступ третьих лиц, иные случаи, угрожающие ущербом Помещению, имуществу или жизни и здоровью людей) незамедлительно принять меры для их устранения, содействовать Арендатору в минимизации ущерба.')
    p('4.2. Арендодатель имеет право:')
    p('4.2.1. Требовать своевременного внесения арендной платы.')
    p('4.2.2. Требовать от Арендатора соблюдения условий настоящего Договора.')
    p('4.2.3. Не чаще одного раза в месяц в присутствии Арендатора проверять состояние Помещения и находящегося в нем имущества в предварительно согласованное с Арендатором время (не менее чем за 24 часа до посещения).')
    p('4.2.4. Получать доступ в Помещение в любое время в случае экстренных ситуаций (аварии, пожар, затопление и т.д.) или при угрозе их возникновения без предварительного согласования с Арендатором.')
    p('4.2.5. В случае существенного нарушения Арендатором условий настоящего Договора потребовать его досрочного расторжения.')
    gap()

    # 5. Права и обязанности Арендатора
    p('5. Права и обязанности Арендатора.', bold=True, size=26)
    p('5.1. Арендатор обязуется:')
    p('5.1.1. Использовать Помещение только для проживания в соответствии с его назначением.')
    p('5.1.2. Своевременно и в полном объеме вносить арендную плату в порядке и размере, определенных настоящим Договором.')
    p('5.1.3. Поддерживать Помещение в надлежащем состоянии, не хуже того, в котором он его получил при заключении Договора, с учетом нормального износа.')
    p('5.1.4. Производить за свой счет текущий ремонт Помещения.')
    p('5.1.5. Бережно относиться к Помещению и находящемуся в нем имуществу.')
    p('5.1.6. Соблюдать правила пользования жилыми помещениями, правила пожарной безопасности, санитарно-гигиенические и экологические требования.')
    p('5.1.7. Не производить перепланировку, переустройство и реконструкцию Помещения без письменного согласия Арендодателя.')
    p('5.1.8. Не сдавать Помещение в субаренду и не передавать свои права и обязанности по настоящему Договору третьим лицам без письменного согласия Арендодателя.')
    p('5.1.9. Не менее чем за {} до окончания срока действия Договора известить Арендодателя о намерении продлить или расторгнуть настоящий Договор.'.format(prolong_notice))
    p('5.1.10. По окончании срока действия Договора или при его досрочном расторжении вернуть Помещение Арендодателю в том состоянии, в котором он его получил, с учетом нормального износа, со всем имуществом согласно Описи.')
    p('5.1.11. Соблюдать тишину и уважать покой соседей, особенно в ночные часы (с 23:00 до 07:00). Не допускать действий, создающих повышенный шум и нарушающих права других жильцов дома.')
    p('5.1.12. Нести полную ответственность за действия своих гостей. Оставлять гостей в Помещении без присутствия Арендатора только с письменного разрешения Арендодателя. Арендатор несет ответственность за любой ущерб, причиненный гостями Помещению или имуществу.')
    p('5.1.13. Проводить серьезные ремонтные работы или осуществлять какие-либо значительные изменения в Помещении (перепланировка, переустройство, реконструкция) только с письменного разрешения Арендодателя.')
    p('5.1.14. Допускать Арендодателя в Помещение для проверки его состояния в соответствии с п. 4.2.3 настоящего Договора.')
    p('5.2. Арендатор имеет право:')
    p('5.2.1. Пользоваться Помещением и находящимся в нем имуществом в соответствии с их назначением.')
    p('5.2.2. С письменного согласия Арендодателя производить за свой счет улучшения Помещения.')
    p('5.2.3. Требовать от Арендодателя своевременного проведения капитального ремонта Помещения.')
    p('5.2.4. В случае невыполнения Арендодателем обязательств по осуществлению капитального ремонта, что создает риск возникновения экстренных ситуаций, Арендатор вправе за свой счет произвести необходимый ремонт и вычесть суммы понесенных расходов из ближайшей подлежащей выплате суммы арендной платы, направив Арендодателю соответствующее письменное уведомление.')
    p('5.3. Арендатор НЕ несет ответственность за естественную амортизацию (износ) Помещения, мебели и оборудования при их надлежащем использовании.')
    gap()

    # 6. Ответственность Сторон
    p('6. Ответственность Сторон.', bold=True, size=26)
    p('6.1. За неисполнение или ненадлежащее исполнение обязательств по настоящему Договору Стороны несут ответственность в соответствии с действующим законодательством Российской Федерации.')
    p('6.2. За нарушение сроков внесения арендной платы Арендатор уплачивает Арендодателю неустойку в размере {}% от суммы задолженности за каждый день просрочки.'.format(fmt_percent(financial['penalty_rate'])))
    p('6.3. В случае порчи или утраты имущества, указанного в Описи имущества (Приложение № 1), Арендатор обязуется возместить Арендодателю причиненный ущерб в полном объеме.')
    p('6.4. Сторона, не исполнившая или ненадлежащим образом исполнившая обязательства по настоящему Договору, обязана возместить другой Стороне причиненные таким неисполнением убытки.')
    gap()

    # 7. Коммунальные и эксплуатационные платежи
    p('7. Коммунальные и эксплуатационные платежи.', bold=True, size=26)
    p('7.1. Арендатор обязуется своевременно и в полном объеме оплачивать коммунальные услуги (электроэнергию, холодное и горячее водоснабжение, водоотведение, отопление) и эксплуатационные расходы (содержание и текущий ремонт общего имущества многоквартирного дома) по действующим тарифам.')
    p('7.2. Оплата коммунальных и эксплуатационных платежей производится Арендатором отдельным платежом на счет Арендодателя (реквизиты указаны в п. 3.3 настоящего Договора) после получения информации о сумме платежа от Арендодателя.')
    p('7.3. Арендодатель обязуется ежемесячно информировать Арендатора о суммах подлежащих оплате коммунальных и эксплуатационных платежей через мессенджеры, электронную почту или по номеру телефона, предоставив копии квитанций или счетов.')
    p('7.4. Арендатор обязуется оплатить коммунальные и эксплуатационные платежи в течение {} с момента получения информации от Арендодателя о сумме платежа.'.format(utility_days))
    p('7.5. Показания счетчиков на момент передачи Помещения Арендатору указаны в Приложении № 2 к настоящему Договору.')
